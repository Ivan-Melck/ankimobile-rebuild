use std::{env, fs, path::PathBuf};
fn main() {
    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let descriptors = env::var_os("DESCRIPTORS_BIN").map(PathBuf::from)
        .unwrap_or_else(|| out.join("../../anki_descriptors.bin"));
    println!("cargo:rerun-if-changed={}", descriptors.display());
    fs::copy(&descriptors, out.join("anki-descriptors.bin")).expect("Anki protobuf descriptors must be generated by anki_proto first");
}
